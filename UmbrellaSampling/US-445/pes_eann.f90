             "Ru","Ru","Ru","Ru","Ru","Ru","Ru","Ru","Ru","Ru",&
             "Ru","Ru","Ru","Ru","Ru","Ru","Ru","Ru","Ru","Ru"]


  integer,save :: ifirst=0
  integer,parameter :: ifrac=0,iforce=1
